"""Переменные, доступные во всех шаблонах."""
from django.conf import settings


def asset_version(request):
    """Единая версия статики для сброса кэша браузера.

    Раньше каждый шаблон нёс свой `?v=20260718-1`, проставленный руками.
    Их набралось под сотню, они разъехались, и часть файлов менялась без
    обновления версии — у пользователя оставалась старая копия. Теперь одно
    значение на весь сайт: поменял статику — поднял ASSET_VERSION.

    На боевом сервере значение стоит задавать переменной окружения
    (например номером сборки), чтобы не править код ради выката.
    """
    return {'ASSET_V': settings.ASSET_VERSION}
